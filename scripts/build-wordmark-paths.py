#!/usr/bin/env python3
# scripts/build-wordmark-paths.py - the SeekSat wordmark ("Seek" + "Sat") and
# "seeksat.com" as SVG outline paths for the server-rendered share cards
# (lib/og/wordmark.mjs). resvg draws nothing with the Exo 2 subset in
# lib/og/fonts/, so the cards fell back to Atkinson; outlines need no font.
#
# Reads lib/og/fonts/Exo2-{SemiBold,Regular}.ttf (the same faces as the
# charts' embed) and writes lib/og/wordmark-paths.mjs. Units are font units
# (1000 per em), y up from the baseline, kerning from the font's GPOS pairs.
# Each run is a list of [x, path data], one per glyph.
#
# Usage (needs fonttools):
#   python3 -m venv .superpowers/venv
#   .superpowers/venv/bin/pip install fonttools
#   .superpowers/venv/bin/python scripts/build-wordmark-paths.py

import json
import os

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

ROOT = os.path.join(os.path.dirname(__file__), "..")
FONTS = os.path.join(ROOT, "lib", "og", "fonts")
OUT = os.path.join(ROOT, "lib", "og", "wordmark-paths.mjs")


def kern_pairs(font):
    """{(left, right): x advance adjustment} from GPOS PairPos format 1."""
    pairs = {}
    if "GPOS" not in font:
        return pairs
    for lookup in font["GPOS"].table.LookupList.Lookup:
        for sub in lookup.SubTable:
            if getattr(sub, "ExtSubTable", None):
                sub = sub.ExtSubTable
            if getattr(sub, "LookupType", None) != 2 and type(sub).__name__ != "PairPos":
                continue
            if sub.Format == 1:
                firsts = sub.Coverage.glyphs
                for first, pset in zip(firsts, sub.PairSet):
                    for rec in pset.PairValueRecord:
                        v = getattr(rec.Value1, "XAdvance", 0) or 0
                        if v:
                            pairs[(first, rec.SecondGlyph)] = v
            elif sub.Format == 2:
                cls1 = sub.ClassDef1.classDefs
                cls2 = sub.ClassDef2.classDefs
                for first in sub.Coverage.glyphs:
                    c1 = cls1.get(first, 0)
                    for second, c2 in list(cls2.items()) + [(g, 0) for g in font.getGlyphOrder() if g not in cls2]:
                        rec = sub.Class1Record[c1].Class2Record[c2]
                        v = getattr(rec.Value1, "XAdvance", 0) or 0
                        if v and (first, second) not in pairs:
                            pairs[(first, second)] = v
    return pairs


def run(font, text, x0=0):
    """Path data for `text` starting at x0, and the x after it."""
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    kerns = kern_pairs(font)
    names = [cmap[ord(ch)] for ch in text]
    parts = []
    x = x0
    for i, name in enumerate(names):
        pen = SVGPathPen(glyphs)
        glyphs[name].draw(pen)
        d = pen.getCommands()
        if d:
            parts.append((x, d))
        x += glyphs[name].width
        if i + 1 < len(names):
            x += kerns.get((name, names[i + 1]), 0)
    return parts, x


def glyph_list(parts):
    """[[x, d], ...]: each glyph's outline and where it starts."""
    return [[x, d] for x, d in parts]


def main():
    semi = TTFont(os.path.join(FONTS, "Exo2-SemiBold.ttf"))
    reg = TTFont(os.path.join(FONTS, "Exo2-Regular.ttf"))
    seek, x = run(semi, "Seek")
    sat, width = run(semi, "Sat", x)
    url, url_width = run(reg, "seeksat.com")
    data = {
        "unitsPerEm": semi["head"].unitsPerEm,
        "seek": glyph_list(seek),
        "sat": glyph_list(sat),
        "width": width,
        "url": glyph_list(url),
        "urlWidth": url_width,
    }
    js = (
        "// lib/og/wordmark-paths.mjs - GENERATED by scripts/build-wordmark-paths.py.\n"
        "// The Exo 2 wordmark and URL as outlines, in font units (y up from the\n"
        "// baseline), one [x, path] per glyph. Drawn by lib/og/wordmark.mjs.\n"
        f"export const WORDMARK_PATHS = {json.dumps(data, indent=2)};\n"
    )
    with open(OUT, "w") as fh:
        fh.write(js)
    print(f"Wrote {os.path.abspath(OUT)} ({len(js)} bytes), width {width}, url {url_width}")


if __name__ == "__main__":
    main()
