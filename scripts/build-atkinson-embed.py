#!/usr/bin/env python3
# scripts/build-atkinson-embed.py - regenerate the Atkinson Hyperlegible Next
# files: the resvg TTFs in lib/og/fonts/ and lib/pass-finder/atkinson-embed.js.
#
# Downloads the variable font from a PINNED google/fonts commit (OFL),
# instances it at wght 400 and 600 (SemiBold: OS/2 usWeightClass 600, name
# table says SemiBold), subsets to the exact code points in UNICODES, then
# writes
#   - lib/og/fonts/AtkinsonHyperlegibleNext-{Regular,SemiBold}.ttf  (resvg)
#   - lib/pass-finder/atkinson-embed.js (woff2 base64 @font-face, browser export)
# After this run: node scripts/build-fonts-embed.mjs  (rebuilds fonts-embed.mjs).
#
# Usage (needs fonttools + brotli):
#   python3 -m venv .superpowers/venv
#   .superpowers/venv/bin/pip install fonttools brotli
#   .superpowers/venv/bin/python scripts/build-atkinson-embed.py

import base64
import io
import os
import urllib.request

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.subset import Subsetter, Options

COMMIT = "95f4904fc8bcf26d3420fe315560c96417c6dec7"  # google/fonts
URL = (f"https://github.com/google/fonts/raw/{COMMIT}/ofl/atkinsonhyperlegiblenext/"
       "AtkinsonHyperlegibleNext%5Bwght%5D.ttf")
# Printable ASCII U+0020-007E, Latin-1 Supplement and Latin Extended-A
# U+00A0-017F (place names such as Zürich, São Paulo, Łódź, İstanbul, which
# the share cards print), plus: Greek Delta and mu, en dash, em dash, curly
# quotes, bullet, ellipsis, minus, approx, le, ge.
UNICODES = (list(range(0x20, 0x7F)) + list(range(0xA0, 0x180)) + [
    0x394, 0x3BC, 0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022,
    0x2026, 0x2212, 0x2248, 0x2264, 0x2265])
FACES = [(400, "Regular"), (600, "SemiBold")]
ROOT = os.path.join(os.path.dirname(__file__), "..")


def build(src: bytes, weight: int, style: str, flavor):
    f = TTFont(io.BytesIO(src))
    instantiateVariableFont(f, {"wght": weight}, inplace=True)
    fam = "Atkinson Hyperlegible Next"
    full = fam if style == "Regular" else f"{fam} {style}"
    ps = f"AtkinsonHyperlegibleNext-{style}"
    f["OS/2"].usWeightClass = weight
    name = f["name"]
    # Static-instance names: family in 1 and 16, style in 2 and 17.
    for nid in (16, 17, 21, 22, 25):
        name.removeNames(nameID=nid)
    for rec_id, val in ((1, fam if style == "Regular" else full), (2, "Regular" if style == "Regular" else "Regular"),
                        (4, full), (6, ps)):
        name.setName(val, rec_id, 3, 1, 0x409)
        name.setName(val, rec_id, 1, 0, 0)
    if style != "Regular":
        name.setName(fam, 16, 3, 1, 0x409); name.setName(style, 17, 3, 1, 0x409)
    opts = Options()
    opts.flavor = flavor
    opts.layout_features = ["kern", "tnum", "liga"]
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    ss = Subsetter(options=opts)
    ss.populate(unicodes=UNICODES)
    ss.subset(f)
    buf = io.BytesIO()
    f.flavor = flavor
    f.save(buf)
    return buf.getvalue()


def main() -> None:
    print(f"Fetching {URL}")
    src = urllib.request.urlopen(URL).read()
    faces = []
    for w, style in FACES:
        ttf = build(src, w, style, None)
        path = os.path.join(ROOT, "lib", "og", "fonts", f"AtkinsonHyperlegibleNext-{style}.ttf")
        open(path, "wb").write(ttf)
        woff2 = build(src, w, style, "woff2")
        print(f"  {w}: ttf {len(ttf)} B, woff2 {len(woff2)} B")
        faces.append(
            "  @font-face {\n"
            "    font-family: 'Atkinson Hyperlegible Next';\n"
            "    font-style: normal;\n"
            f"    font-weight: {w};\n"
            "    font-display: block;\n"
            f"    src: url(data:font/woff2;base64,{base64.b64encode(woff2).decode()}) format('woff2');\n"
            "  }\n")
    js = (
        "// lib/pass-finder/atkinson-embed.js - GENERATED by\n"
        "// scripts/build-atkinson-embed.py. Atkinson Hyperlegible Next (OFL),\n"
        "// weights 400 and 600, subset, as base64 woff2 @font-face rules. Embedded so the\n"
        "// chart PNG export (SVG in an <img>, data: URIs only) has the font. Same\n"
        "// approach as exo2-embed.js.\n"
        "export const ATKINSON_FONT_FACE = `\n" + "".join(faces) + "`;\n\n"
        "export const ATKINSON_STACK = \"'Atkinson Hyperlegible Next', system-ui, -apple-system, sans-serif\";\n")
    open(os.path.join(ROOT, "lib", "pass-finder", "atkinson-embed.js"), "w").write(js)
    for w, style in FACES:
        t = TTFont(os.path.join(ROOT, "lib", "og", "fonts", f"AtkinsonHyperlegibleNext-{style}.ttf"))
        print(style, "usWeightClass", t["OS/2"].usWeightClass,
              {n.nameID: n.toUnicode() for n in t["name"].names if n.platformID == 3 and n.nameID in (1, 2, 4, 6, 16, 17)})


if __name__ == "__main__":
    main()
