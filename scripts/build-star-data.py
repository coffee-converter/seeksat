#!/usr/bin/env python3
"""Write lib/map/star-data.mjs from the Yale Bright Star Catalogue (BSC5).

Source: Hoffleit & Warren, The Bright Star Catalogue, 5th Revised Ed. (1991),
public domain, as bsc5.dat from http://tdc-www.harvard.edu/catalogs/bsc5.html
(the same file as CDS V/50). Usage: build-star-data.py path/to/bsc5.dat
Keeps stars to MAG_LIMIT; J2000 positions; B-V where given.
"""
import sys

MAG_LIMIT = 5.5
OUT = 'lib/map/star-data.mjs'

stars = []
for line in open(sys.argv[1], encoding='latin-1'):
    line = line.rstrip('\n').ljust(197)
    try:
        rah, ram, ras = int(line[75:77]), int(line[77:79]), float(line[79:83])
        sign = -1 if line[83] == '-' else 1
        ded, dem, des = int(line[84:86]), int(line[86:88]), int(line[88:90])
        vmag = float(line[102:107])
    except ValueError:
        continue  # novae and entries without a J2000 position
    if vmag > MAG_LIMIT:
        continue
    bv = line[109:114].strip()
    ra = rah + ram / 60 + ras / 3600
    dec = sign * (ded + dem / 60 + des / 3600)
    stars.append((round(ra * 1000), round(dec * 100), round(vmag * 100), round(float(bv) * 100) if bv else 65))

stars.sort(key=lambda s: s[2])  # brightest first
flat = ','.join(f'{a},{b},{c},{d}' for a, b, c, d in stars)
with open(OUT, 'w') as f:
    f.write(f'''// lib/map/star-data.mjs - GENERATED by scripts/build-star-data.py; do not edit.
// The {len(stars)} stars to magnitude {MAG_LIMIT} of the Yale Bright Star Catalogue,
// 5th revised edition (Hoffleit & Warren 1991, public domain), brightest first.
// Four integers per star: right ascension (hours x 1000), declination
// (degrees x 100), V magnitude (x 100), B-V colour index (x 100; 0.65, a
// Sun-like colour, where the catalogue has none). J2000.
export const STAR_COUNT = {len(stars)};
export const STARS = [{flat}];
''')
print(f'Wrote {OUT}: {len(stars)} stars')
